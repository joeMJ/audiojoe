#!/usr/bin/env python3
"""Translations: po/de.po is the source; generates the tables of both clients and
reports texts used in the code that have no translation.

    tools/i18n.py          generate clients/web/src/app/de.g.json and clients/app/lib/l10n_de.g.dart
    tools/i18n.py --check  only report missing / unused translations (exit 1 if missing)
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent


def unquote(s: str) -> str:
    return json.loads('"' + s + '"')


def read_po(path: pathlib.Path) -> dict:
    entries, msgid, msgstr, cur = {}, None, None, None
    for line in path.read_text().splitlines() + [""]:
        line = line.strip()
        if line.startswith("msgid "):
            if msgid:
                entries[msgid] = msgstr
            msgid, msgstr, cur = unquote(line[7:-1]), "", "id"
        elif line.startswith("msgstr "):
            msgstr, cur = unquote(line[8:-1]), "str"
        elif line.startswith('"') and cur:
            if cur == "id":
                msgid += unquote(line[1:-1])
            else:
                msgstr += unquote(line[1:-1])
        elif not line:
            if msgid:
                entries[msgid] = msgstr
            msgid, cur = None, None
    return {k: v for k, v in entries.items() if k and v}


def used_texts() -> set:
    found = set()
    for path, pat in [
        ("clients/web/src/app", re.compile(r'\bt\("((?:[^"\\]|\\.)*)"')),
        ("clients/web/src/testcar", re.compile(r'\bt\("((?:[^"\\]|\\.)*)"')),
        ("clients/app/lib", re.compile(r"\bt\('((?:[^'\\]|\\.)*)'")),
    ]:
        for f in (root / path).rglob("*"):
            if f.suffix in (".ts", ".dart") and not f.name.endswith(".g.dart"):
                found.update(m.group(1) for m in pat.finditer(f.read_text()))
    # Labels passed through variables (navigation).
    for f in [root / "clients/web/src/app/ui.ts", root / "clients/app/lib/ui/shell.dart"]:
        found.update(re.findall(r"""['"](Now playing|Continue|Podcasts|Audiobooks|Music|Offline|Settings)['"]""", f.read_text()))
    return found


de = read_po(root / "po/de.po")
used = used_texts()
missing = sorted(used - de.keys())
unused = sorted(de.keys() - used)
for m in missing:
    print(f"missing translation: {m!r}")
for u in unused:
    print(f"unused translation:  {u!r}")
if "--check" in sys.argv:
    sys.exit(1 if missing else 0)

(root / "clients/web/src/app/de.g.json").write_text(json.dumps(de, ensure_ascii=False, indent=1, sort_keys=True) + "\n")
dart = ["// Generated by tools/i18n.py from po/de.po – do not edit.", "", "const deStrings = <String, String>{"]
for k in sorted(de):
    dart.append(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(de[k], ensure_ascii=False)},".replace("$", "\\$"))
dart.append("};")
(root / "clients/app/lib/l10n_de.g.dart").write_text("\n".join(dart) + "\n")
print(f"{len(de)} translations written")
