#!/usr/bin/env python3
"""Generates clients/app/lib/tokens.g.dart from design/tokens.json (shared design tokens).

    tools/gen-tokens.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
tokens = json.loads((root / "design/tokens.json").read_text())


def color(v: str) -> str:
    return "Color(0xFF" + v.lstrip("#").upper() + ")"


out = ["// Generated by tools/gen-tokens.py from design/tokens.json – do not edit.", "",
       "import 'package:flutter/material.dart';", ""]
for mode in ("light", "dark"):
    out.append(f"class {mode.capitalize()}Tokens {{")
    for k, v in tokens["color"][mode].items():
        out.append(f"  static const {k} = {color(v)};")
    out.append("}")
    out.append("")
out.append("class SizeTokens {")
for k, v in tokens["size"].items():
    out.append(f"  static const double {k} = {float(v)};")
out.append("}")
(root / "clients/app/lib/tokens.g.dart").write_text("\n".join(out) + "\n")
print("clients/app/lib/tokens.g.dart written")
